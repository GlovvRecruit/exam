// 정규화: 공백·구두점·대소문자 차이 무시
function normalize(s) {
  return (s || "")
    .toLowerCase()
    .replace(/\s+/g, " ")
    .replace(/[.,!?;:'"()\[\]]/g, " ")
    .trim();
}

// 단답형 채점: 키워드 그룹마다 1개 이상 매칭되면 그룹 통과
// 통과한 그룹 비율 × 배점
function gradeShortAnswer(userAnswer, item) {
  const ans = normalize(userAnswer);
  if (!ans) return 0;
  const groups = item.keywords || [];
  if (groups.length === 0) return 0;
  let passed = 0;
  for (const group of groups) {
    if (group.some(kw => ans.includes(normalize(kw)))) {
      passed++;
    }
  }
  const ratio = passed / groups.length;
  // 전체 매칭 = 만점, 부분 매칭 = 비율 × 점수, 단 50% 미만이면 0점
  if (ratio === 1) return item.points;
  if (ratio >= 0.5) return Math.floor(item.points * ratio);
  return 0;
}

// 객관식 채점
function gradeMCQ(userAnswers) {
  let score = 0;
  const detail = [];
  for (const q of MCQ) {
    const ua = parseInt(userAnswers[q.id], 10);
    const correct = ua === q.answer;
    if (correct) score += q.points;
    detail.push({ id: q.id, user: ua, correct: q.answer, ok: correct, points: correct ? q.points : 0 });
  }
  return { score, detail };
}

// 단답형 채점
function gradeShort(userAnswers) {
  let score = 0;
  const detail = [];
  for (const q of SHORT) {
    const ua = userAnswers[q.id] || "";
    const earned = gradeShortAnswer(ua, q);
    score += earned;
    detail.push({ id: q.id, user: ua, max: q.points, earned, answer_text: q.answer_text });
  }
  return { score, detail };
}

// 전체 자동 채점
function autoGrade(mcqAnswers, shortAnswers) {
  const mcq = gradeMCQ(mcqAnswers);
  const short = gradeShort(shortAnswers);
  return {
    total: mcq.score + short.score,
    mcq,
    short,
  };
}
