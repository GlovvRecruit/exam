  // text: 응시자 원문, examType: 'onboarding'|'sales', areaKey: 'all'|'phone'|'meeting'
  function gradeArea(text, examType, areaKey) {
    const exam = EXAMS[examType];
    const points = flatten(exam.areas[areaKey].sections);
    const norm = normalize(text);
    let total = 0, got = 0; const hit = [], miss = [];
    points.forEach(p => {
      total += p.w;
      if (pointHit(norm, p)) { got += p.w; hit.push(p); } else miss.push(p);
    });
    const raw = total ? Math.round(got / total * 100) : 0;
    return { score: calibrate(raw, exam.anchorRaw, exam.anchorScore), raw, hit, miss, total, got };
  }

