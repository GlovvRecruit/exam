  function normalize(s) {
    return (s || "").toLowerCase().replace(/\s+/g, "")
      .replace(/[.,!?~·"'“”‘’「」\[\]\(\)<>:;\-_/\\#@%]/g, "");
  }
  function flatten(sections) {
    const out = [];
    sections.forEach(sec => sec.points.forEach(p => out.push(Object.assign({ section: sec.title }, p))));
    return out;
  }
  // 정규화 시 '%' 가 제거되므로 토큰도 같은 방식으로 정규화해서 비교
  function pointHit(norm, p) { return p.any.some(pat => pat.every(t => norm.includes(normalize(t)))); }
  function calibrate(raw, anchorRaw, anchorScore) {
    if (raw <= anchorRaw) return Math.round(raw * anchorScore / anchorRaw);
    return Math.round(anchorScore + (raw - anchorRaw) * (100 - anchorScore) / (100 - anchorRaw));
  }

